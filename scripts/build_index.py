#!/usr/bin/env python3
"""Rebuild skills/nasa-guidance-docs/references/INDEX.md from each page's first heading and owner row."""
import glob, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "skills", "nasa-guidance-docs", "references")

def rows(sub, field):
    out = []
    for p in sorted(glob.glob(os.path.join(ROOT, sub, "*.md"))):
        name = os.path.basename(p)
        if name.startswith("_"):
            continue
        text = open(p, encoding="utf-8").read()
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), name)
        m = re.search(r"\|\s*\*\*%s\*\*\s*\|\s*(.*?)\s*\|\s*$" % re.escape(field), text, re.M)
        cell = (m.group(1) if m else "").replace("|", "/")
        cell = re.sub(r"\s+", " ", cell)
        if len(cell) > 90:
            cell = cell[:87].rstrip() + "..."
        out.append("| `%s/%s` | %s | %s |" % (sub, name, title.replace("|", "/"), cell))
    return out

doc = rows("documents", "Owner office")
ext = rows("external", "Publisher / owner")
body = ["# Index of pages", "",
        "Generated by `scripts/build_index.py`; do not edit by hand.", "",
        "## NASA and JPL documents (%d)" % len(doc), "",
        "| Page | Document | Owner |", "|---|---|---|"] + doc + ["",
        "## External documents (%d): comparison only, never NASA coverage" % len(ext), "",
        "| Page | Document | Publisher |", "|---|---|---|"] + ext + [""]
open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8").write("\n".join(body))
print(len(doc), len(ext))
